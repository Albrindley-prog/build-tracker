// Builds Word documents with the `docx` library (loaded as a global in the browser,
// or assigned to globalThis.docx when tested in Node). Returns docx Document objects;
// the caller turns them into a file with docx.Packer.
(function (root) {
  'use strict';

  const {
    Document, Paragraph, TextRun, HeadingLevel, AlignmentType, BorderStyle,
    Footer, PageNumber, LevelFormat, ShadingType,
  } = root.docx;

  const INK = '1F3A5F';
  const GREY = '6B7280';
  const ACCENT = '2457D6';
  const BULLETS = 'summary-bullets';

  function longDateTime(ts) {
    const d = new Date(ts);
    const date = d.toLocaleDateString('en-GB', {
      weekday: 'long', day: 'numeric', month: 'long', year: 'numeric',
    });
    const time = d.toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit', hour12: false });
    return `${date}, ${time}`;
  }

  // One Paragraph per line of text, so line breaks you typed are kept.
  function bodyParagraphs(text) {
    const trimmed = (text || '').replace(/\s+$/, '');
    if (!trimmed) {
      return [new Paragraph({
        children: [new TextRun({ text: '(No text in this note.)', italics: true, color: GREY })],
      })];
    }
    return trimmed.split(/\r?\n/).map((line) => new Paragraph({ children: [new TextRun(line)] }));
  }

  // Shaded box under the date line: summary, then "Action points" (bullets, or "None").
  // note.summary = { text, actions: string[], model }
  function summaryBlocks(summary) {
    if (!summary || !summary.text) return [];
    const box = {
      shading: { type: ShadingType.CLEAR, fill: 'EEF3FB', color: 'auto' },
      border: { left: { style: BorderStyle.SINGLE, size: 24, color: ACCENT, space: 8 } },
    };
    const label = (text, extra) => new Paragraph({
      ...box,
      indent: { left: 270 },
      keepNext: true,
      spacing: { before: 60, after: 40 },
      children: [
        new TextRun({ text, bold: true, color: INK }),
        ...(extra ? [new TextRun({ text: extra, color: GREY, size: 18 })] : []),
      ],
    });

    const actions = Array.isArray(summary.actions) ? summary.actions : [];
    const actionParagraphs = actions.length
      ? actions.map((a) => new Paragraph({
        ...box,
        numbering: { reference: BULLETS, level: 0 },
        spacing: { after: 40 },
        children: [new TextRun(a)],
      }))
      : [new Paragraph({ ...box, indent: { left: 270 }, spacing: { after: 40 }, children: [new TextRun('None')] })];

    return [
      label('Summary', summary.model ? `   AI-generated by ${summary.model}` : '   AI-generated'),
      new Paragraph({ ...box, indent: { left: 270 }, spacing: { after: 100 }, children: [new TextRun(summary.text)] }),
      label('Action points'),
      ...actionParagraphs,
      new Paragraph({
        keepNext: true,
        spacing: { before: 200, after: 60 },
        children: [new TextRun({ text: 'FULL NOTE', bold: true, color: GREY, size: 16 })],
      }),
    ];
  }

  // Heading + date/time line + summary (if any) + body for a single note.
  function noteBlocks(note) {
    return [
      new Paragraph({
        heading: HeadingLevel.HEADING_1,
        children: [new TextRun(note.title || 'Untitled note')],
      }),
      new Paragraph({
        spacing: { after: 160 },
        border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: 'BFC5CF', space: 4 } },
        children: [new TextRun({ text: longDateTime(note.createdAt), italics: true, color: GREY, size: 20 })],
      }),
      ...summaryBlocks(note.summary),
      ...bodyParagraphs(note.text),
    ];
  }

  function makeDocument(children, title) {
    return new Document({
      creator: 'Voice Notes',
      title,
      numbering: {
        config: [{
          reference: BULLETS,
          levels: [{
            level: 0,
            format: LevelFormat.BULLET,
            text: '•',
            alignment: AlignmentType.LEFT,
            style: { paragraph: { indent: { left: 540, hanging: 270 } } },
          }],
        }],
      },
      styles: {
        default: {
          document: {
            run: { font: 'Calibri', size: 22 },
            paragraph: { spacing: { after: 120, line: 276 } },
          },
        },
        paragraphStyles: [
          {
            id: 'Title', name: 'Title', basedOn: 'Normal', next: 'Normal', quickFormat: true,
            run: { size: 44, bold: true, color: INK },
            paragraph: { spacing: { after: 60 } },
          },
          {
            id: 'Heading1', name: 'Heading 1', basedOn: 'Normal', next: 'Normal', quickFormat: true,
            run: { size: 32, bold: true, color: INK },
            paragraph: { spacing: { before: 360, after: 60 }, keepNext: true, outlineLevel: 0 },
          },
        ],
      },
      sections: [{
        properties: {
          page: {
            size: { width: 11906, height: 16838 }, // A4
            margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 },
          },
        },
        footers: {
          default: new Footer({
            children: [new Paragraph({
              alignment: AlignmentType.CENTER,
              children: [new TextRun({
                children: ['Page ', PageNumber.CURRENT, ' of ', PageNumber.TOTAL_PAGES],
                size: 18, color: GREY,
              })],
            })],
          }),
        },
        children,
      }],
    });
  }

  // note: { title, text, createdAt }
  function buildNoteDocument(note) {
    return makeDocument(noteBlocks(note), note.title || 'Voice note');
  }

  // notes: array of { title, text, createdAt }. Sorted newest first here.
  function buildAllNotesDocument(notes, exportedAt = Date.now()) {
    const sorted = [...notes].sort((a, b) => b.createdAt - a.createdAt);
    const children = [
      new Paragraph({ style: 'Title', children: [new TextRun('Voice Notes')] }),
      new Paragraph({
        spacing: { after: 120 },
        children: [new TextRun({
          text: `${sorted.length} ${sorted.length === 1 ? 'note' : 'notes'}, newest first. Exported ${longDateTime(exportedAt)}.`,
          color: GREY, size: 20,
        })],
      }),
    ];
    sorted.forEach((note) => children.push(...noteBlocks(note)));
    return makeDocument(children, 'Voice Notes');
  }

  root.VoiceExport = { buildNoteDocument, buildAllNotesDocument, longDateTime };
})(typeof globalThis !== 'undefined' ? globalThis : window);
